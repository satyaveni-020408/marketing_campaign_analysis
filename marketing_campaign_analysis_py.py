# -----------------------------
# 5. HANDLE MISSING VALUES
# -----------------------------

# Numerical columns:
# Fill missing values with median

numeric_columns = df.select_dtypes(include=np.number).columns

for column in numeric_columns:
    if df[column].isnull().sum() > 0:
        df[column] = df[column].fillna(df[column].median())


# Categorical columns:
# Fill missing values with mode

categorical_columns = df.select_dtypes(include="object").columns

for column in categorical_columns:
    if df[column].isnull().sum() > 0:
        df[column] = df[column].fillna(df[column].mode()[0])


print("\nMissing values after handling:")
print(df.isnull().sum())


# -----------------------------
# 6. DATA CLEANING
# -----------------------------

# Convert Duration if it contains "days"
if "Duration" in df.columns:
    if df["Duration"].dtype == "object":
        df["Duration"] = (
            df["Duration"]
            .astype(str)
            .str.replace(" days", "", regex=False)
            .str.replace(" day", "", regex=False)
        )
        df["Duration"] = pd.to_numeric(df["Duration"], errors="coerce")


# Convert Acquisition_Cost into numeric
if "Acquisition_Cost" in df.columns:
    if df["Acquisition_Cost"].dtype == "object":
        df["Acquisition_Cost"] = (
            df["Acquisition_Cost"]
            .astype(str)
            .str.replace("$", "", regex=False)
            .str.replace(",", "", regex=False)
        )

    df["Acquisition_Cost"] = pd.to_numeric(
        df["Acquisition_Cost"], errors="coerce"
    )


# Convert Date to datetime
if "Date" in df.columns:
    df["Date"] = pd.to_datetime(df["Date"], errors="coerce")


